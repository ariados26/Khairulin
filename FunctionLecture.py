# Задача №17
# Создай декоратор before, который перед выполнением декорированной функции выводит:
# Начинаем выполнение
# Создай функцию show_name, которая выводит:
# Иван
# Примени декоратор @before к функции show_name и вызови её.
# Ожидаемый порядок вывода:
# Начинаем выполнение
# Иван

def before(func):
    def wrapper():
        print(f"Начинаем выполнение")
        func()
    return wrapper
@before
def show_name():
    print(f"Иван")
show_name()

# Задача №18 — последняя
# Создай декоратор after, который после выполнения декорированной функции выводит:
# Функция завершена
# Создай функцию say_hello, которая выводит:
# Привет!
# Примени @after и вызови say_hello().
# Ожидаемый порядок вывода:
# Привет!
# Функция завершена

def after(func):
    def wrapper():
        func()
        print(f"Функция завершена")
    return wrapper

@after
def say_hello():
    print(f"Привет!")
say_hello()