# Задача №6
# Создай декоратор my_decorator, который при вызове декорированной функции должен сначала вывести:
# Начало
# Затем должна выполниться функция, которая выводит:
# Привет!
# Используй @my_decorator для применения декоратора.

def my_decorator(func):
    def wrapper():
        print(f"Начало")
        func()
    return wrapper
@my_decorator
def say_hello():
    print(f"Привет!")
say_hello()

