# Задача №1 — оператор if
# Создай переменную:
# age = 20
# Проверь с помощью if, является ли возраст 18 или больше.
# Если условие выполняется, выведи:
# Совершеннолетний

age = 20
if age >= 18:
    print("Совершеннолетний")

# Задача №2 — оператор else
# Создай переменную:
# temperature = 15
# Напиши условие:
# если температура выше 20 — вывести Тепло;
# во всех остальных случаях — вывести Прохладно.
# Используй if и else.

temperature = 15
if temperature > 20:
    print("Тепло")
else:
    print("Прохладно")

# Задача №3 — оператор elif
# Создай переменную:
# score = 7
# Проверь оценку:
# если score равен 10 — выведи Отлично;
# если score равен 7 — выведи Хорошо;
# во всех остальных случаях — выведи Нужно постараться.
# Используй if, elif и else.

score = 7
if score == 10:
    print("Отлично")
elif score == 7:
    print("Хорошо")
else:
    print("Нужно постараться.")

# Задача №4 — логические операции
# Создай две переменные:
# age = 25
# has_ticket = True
# Проверь с помощью логического оператора and:
# если возраст 18 или больше и есть билет — выведи Можно войти;
# иначе ничего выводить не нужно.
# Используй if.

age = 25
has_ticket = True
if age >= 18 and has_ticket:
    print("Можно войти")

# Задача №5 — тернарный оператор
# Создай переменную:
# age = 20
# С помощью тернарного оператора создай переменную status:
# если возраст 18 или больше → "Совершеннолетний"
# иначе → "Несовершеннолетний"
# После этого выведи status.

