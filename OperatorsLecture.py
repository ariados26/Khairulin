# Задача №11 — логические операции and и or
# Создай переменные:
# age = 20
# has_ticket = True
# has_invitation = False
# С помощью if проверь условие:
# возраст 18 или больше
# и при этом есть билет или приглашение
# Если условие выполняется, выведи:
# Вход разрешён
# Используй and и or.

age = 20
has_ticket = True
has_invitation = False
if age >= 18 and (has_ticket or has_invitation):
    print("Вход разрешён")

# Задача №12 — if / else
# Создай переменную:
