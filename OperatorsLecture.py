# Задача №9 — if / elif / else
# Создай переменную:
# day = 2
# Проверь значение:
# если day == 1 → вывести Понедельник;
# если day == 2 → вывести Вторник;
# если day == 3 → вывести Среда;
# во всех остальных случаях → вывести Другой день.
# Используй if, elif и else.

day = 2
if day == 1:
    print("Понедельник")
elif day == 2:
    print("Вторник")
elif day == 3:
    print("Среда")
else:
    print("Другой день")

# Задача №10 — тернарный оператор
# Создай переменную:
# number = 7
